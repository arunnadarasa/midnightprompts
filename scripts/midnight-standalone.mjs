#!/usr/bin/env bun
// One-command wrapper for the Midnight standalone stack (node + indexer + proof-server).
// Usage:
//   bun scripts/midnight-standalone.mjs up      # pull + start + wait for readiness
//   bun scripts/midnight-standalone.mjs down    # stop + remove
//   bun scripts/midnight-standalone.mjs status  # container + endpoint health
//   bun scripts/midnight-standalone.mjs logs [service]
//
// Requires: Docker Desktop (macOS/Windows) or Docker Engine (Linux) running.

import { spawn, spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { platform } from "node:os";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import net from "node:net";
import { MIDNIGHT_MATRIX } from "../src/lib/midnight-matrix.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const STACK_DIR = resolve(ROOT, ".midnight");
const COMPOSE_FILE = resolve(STACK_DIR, "standalone.docker-compose.yml");
const PROJECT_NAME = "midnight-standalone";

const c = {
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
  red: (s) => `\x1b[31m${s}\x1b[0m`,
  green: (s) => `\x1b[32m${s}\x1b[0m`,
  yellow: (s) => `\x1b[33m${s}\x1b[0m`,
  cyan: (s) => `\x1b[36m${s}\x1b[0m`,
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
};

// Canonical standalone compose file. Pinned image tags mirror the local-dev
// row of the Midnight Support Matrix (see src/lib/midnight-matrix.ts).
const COMPOSE = `# Auto-generated by scripts/midnight-standalone.mjs — do not edit by hand.
# Regenerate: bun scripts/midnight-standalone.mjs up
name: ${PROJECT_NAME}
services:
  proof-server:
    image: midnightntwrk/proof-server:${MIDNIGHT_MATRIX.localStack.proofServer}
    container_name: midnight-standalone-proof-server
    ports:
      - "6300:6300"
    command: ["midnight-proof-server", "-v"]
    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://localhost:6300/health || exit 1"]
      interval: 5s
      timeout: 3s
      retries: 20

  node:
    image: midnightntwrk/midnight-node:${MIDNIGHT_MATRIX.localStack.node}
    container_name: midnight-standalone-node
    ports:
      - "9944:9944"
    environment:
      CFG_PRESET: "dev"
      SHOW_CONFIG: "false"
    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://localhost:9944 --header='Content-Type: application/json' --post-data='{\\"jsonrpc\\":\\"2.0\\",\\"method\\":\\"system_chain\\",\\"id\\":1}' >/dev/null 2>&1 || exit 1"]
      interval: 5s
      timeout: 3s
      retries: 30

  indexer:
    image: midnightntwrk/indexer-standalone:${MIDNIGHT_MATRIX.localStack.indexer}
    container_name: midnight-standalone-indexer
    ports:
      - "8088:8088"
    environment:
      RUST_LOG: "indexer=info,chain_indexer=info,indexer_api=info,warn"
      APP__INFRA__NODE__URL: "ws://node:9944"
    depends_on:
      node:
        condition: service_healthy
    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://localhost:8088/api/v4/graphql -q --header='Content-Type: application/json' --post-data='{\\"query\\":\\"{__typename}\\"}' >/dev/null 2>&1 || exit 1"]
      interval: 5s
      timeout: 3s
      retries: 30
`;

const HELP = `${c.bold("midnight-standalone")} — one-command Midnight local stack

  ${c.cyan("bun scripts/midnight-standalone.mjs up")}       ${c.dim("pull images, start node+indexer+proof, wait for green")}
  ${c.cyan("bun scripts/midnight-standalone.mjs down")}     ${c.dim("stop + remove containers")}
  ${c.cyan("bun scripts/midnight-standalone.mjs status")}   ${c.dim("container health + endpoint probes")}
  ${c.cyan("bun scripts/midnight-standalone.mjs logs [svc]")} ${c.dim("tail logs (svc: node|indexer|proof-server)")}

Endpoints (after ${c.cyan("up")}):
  node          ws://localhost:9944
  indexer HTTP  http://localhost:8088/api/v4/graphql
  indexer WS    ws://localhost:8088/api/v4/graphql/ws
  proof server  http://localhost:6300

Health page: ${c.cyan("/undeployed-preflight")}
`;

function run(cmd, args, opts = {}) {
  return new Promise((res) => {
    const child = spawn(cmd, args, { stdio: "inherit", ...opts });
    child.on("close", (code) => res(code ?? 1));
    child.on("error", () => res(1));
  });
}

function runSilent(cmd, args) {
  const r = spawnSync(cmd, args, { encoding: "utf8" });
  return { code: r.status ?? 1, stdout: r.stdout ?? "", stderr: r.stderr ?? "" };
}

function checkDocker() {
  const info = runSilent("docker", ["info", "--format", "{{.ServerVersion}}"]);
  if (info.code !== 0) {
    console.error(c.red("✗ Docker is not reachable."));
    const p = platform();
    if (p === "darwin" || p === "win32") {
      console.error(
        `  Start Docker Desktop and wait for the whale icon to stop animating.\n` +
          `  ${c.dim(p === "darwin" ? "macOS: open -a Docker" : "Windows: launch Docker Desktop from Start")}`,
      );
    } else {
      console.error(
        `  Start the engine:  ${c.cyan("sudo systemctl start docker")}\n` +
          `  Then confirm:      ${c.cyan("docker info")}`,
      );
    }
    return false;
  }
  const compose = runSilent("docker", ["compose", "version"]);
  if (compose.code !== 0) {
    console.error(c.red("✗ 'docker compose' plugin missing."));
    console.error(
      `  Docker Desktop bundles it; on Linux install ${c.cyan("docker-compose-plugin")}.`,
    );
    return false;
  }
  return true;
}

function portOpen(port, host = "127.0.0.1", timeoutMs = 400) {
  return new Promise((res) => {
    const sock = new net.Socket();
    let done = false;
    const finish = (open) => {
      if (done) return;
      done = true;
      sock.destroy();
      res(open);
    };
    sock.setTimeout(timeoutMs);
    sock.once("connect", () => finish(true));
    sock.once("timeout", () => finish(false));
    sock.once("error", () => finish(false));
    sock.connect(port, host);
  });
}

async function checkPortsFree() {
  const ports = [9944, 8088, 6300];
  const busy = [];
  for (const p of ports) if (await portOpen(p)) busy.push(p);
  if (busy.length === 0) return true;
  // Might already be OUR stack — check container names first.
  const ps = runSilent("docker", ["ps", "--format", "{{.Names}}"]);
  const ours = ps.stdout.includes(`${PROJECT_NAME}-`) || ps.stdout.includes("midnight-standalone-");
  if (ours) return true;
  console.error(
    c.yellow(`⚠ Ports already in use: ${busy.join(", ")}. ` +
      `Stop the process holding them, or run ${c.cyan("down")} first.`),
  );
  return false;
}

function writeCompose() {
  if (!existsSync(STACK_DIR)) mkdirSync(STACK_DIR, { recursive: true });
  writeFileSync(COMPOSE_FILE, COMPOSE, "utf8");
}

async function waitEndpoint(label, probe, { attempts = 60, delayMs = 2000 } = {}) {
  process.stdout.write(`  ${c.dim("↻")} ${label} `);
  for (let i = 0; i < attempts; i++) {
    try {
      if (await probe()) {
        process.stdout.write(`${c.green("ok")}\n`);
        return true;
      }
    } catch {}
    await new Promise((r) => setTimeout(r, delayMs));
    if (i % 5 === 4) process.stdout.write(".");
  }
  process.stdout.write(`${c.red("timeout")}\n`);
  return false;
}

async function probeProof() {
  const r = await fetch("http://localhost:6300/health").catch(() => null);
  return !!r && r.ok;
}
async function probeIndexer() {
  const r = await fetch("http://localhost:8088/api/v4/graphql", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ query: "{__typename}" }),
  }).catch(() => null);
  return !!r && r.ok;
}
async function probeNode() {
  // Substrate node speaks WS on 9944; a TCP connect is a sufficient liveness check
  // (a full JSON-RPC probe would need a WS client). node service healthcheck runs
  // inside docker with correct headers already.
  return await portOpen(9944);
}

async function up() {
  if (!checkDocker()) process.exit(1);
  if (!(await checkPortsFree())) process.exit(1);

  console.log(c.bold("→ writing compose file"), c.dim(COMPOSE_FILE));
  writeCompose();

  console.log(c.bold("→ pulling images (first run may take a few minutes)"));
  const pull = await run("docker", ["compose", "-f", COMPOSE_FILE, "pull"]);
  if (pull !== 0) {
    console.error(c.red("✗ docker compose pull failed"));
    process.exit(pull);
  }

  console.log(c.bold("→ starting containers"));
  const upCode = await run("docker", ["compose", "-f", COMPOSE_FILE, "up", "-d"]);
  if (upCode !== 0) {
    console.error(c.red("✗ docker compose up failed"));
    process.exit(upCode);
  }

  console.log(c.bold("→ waiting for readiness"));
  const proofOk = await waitEndpoint("proof server (http://localhost:6300/health)", probeProof);
  const nodeOk = await waitEndpoint("node          (ws://localhost:9944)", probeNode);
  const idxOk = await waitEndpoint("indexer       (http://localhost:8088/api/v4/graphql)", probeIndexer);

  if (proofOk && nodeOk && idxOk) {
    console.log("");
    console.log(c.green(c.bold("✓ Midnight standalone stack is up.")));
    console.log(`  ${c.dim("node")}          ws://localhost:9944`);
    console.log(`  ${c.dim("indexer HTTP")}  http://localhost:8088/api/v4/graphql`);
    console.log(`  ${c.dim("indexer WS")}    ws://localhost:8088/api/v4/graphql/ws`);
    console.log(`  ${c.dim("proof server")}  http://localhost:6300`);
    console.log("");
    console.log(`  Open ${c.cyan("/undeployed-preflight")} in the app to verify from your browser.`);
    console.log(`  Point Lace: Settings → Network → Custom → RPC = ${c.cyan("ws://localhost:9944")}.`);
    console.log(`  Deploy:     ${c.cyan("VITE_NETWORK_ID=undeployed bun scripts/deploy-midnight.mjs")}`);
    console.log("");
  } else {
    console.log("");
    console.log(c.yellow("⚠ Some endpoints did not come up in time."));
    console.log(`  Tail logs:   ${c.cyan("bun scripts/midnight-standalone.mjs logs")}`);
    console.log(`  Status:      ${c.cyan("bun scripts/midnight-standalone.mjs status")}`);
    process.exit(2);
  }
}

async function down() {
  if (!existsSync(COMPOSE_FILE)) writeCompose();
  await run("docker", ["compose", "-f", COMPOSE_FILE, "down", "--remove-orphans"]);
  console.log(c.green("✓ stack stopped"));
}

async function status() {
  if (!checkDocker()) process.exit(1);
  console.log(c.bold("Containers:"));
  await run("docker", [
    "compose",
    "-f",
    existsSync(COMPOSE_FILE) ? COMPOSE_FILE : "/dev/null",
    "ps",
  ]);
  console.log("");
  console.log(c.bold("Endpoints:"));
  const results = await Promise.all([
    probeProof().then((ok) => ["proof server ", ok]),
    probeNode().then((ok) => ["node WS      ", ok]),
    probeIndexer().then((ok) => ["indexer HTTP ", ok]),
  ]);
  for (const [label, ok] of results) {
    console.log(`  ${label}  ${ok ? c.green("ok") : c.red("down")}`);
  }
}

async function logs(svc) {
  if (!existsSync(COMPOSE_FILE)) {
    console.error(c.red("✗ compose file missing — run 'up' first"));
    process.exit(1);
  }
  const args = ["compose", "-f", COMPOSE_FILE, "logs", "-f", "--tail=200"];
  if (svc) args.push(svc);
  await run("docker", args);
}

const [, , cmd, ...rest] = process.argv;
switch (cmd) {
  case "up":     await up(); break;
  case "down":   await down(); break;
  case "status": await status(); break;
  case "logs":   await logs(rest[0]); break;
  case "help":
  case "-h":
  case "--help":
  case undefined: console.log(HELP); break;
  default:
    console.error(c.red(`Unknown command: ${cmd}`));
    console.log(HELP);
    process.exit(1);
}
